-- EgyBook v99 independent chat/call phase
-- Run in Supabase SQL Editor. This creates a minimal WebRTC signaling table;
-- media itself is peer-to-peer and is never stored in this table.
create table if not exists public.call_signals (
  id bigint generated by default as identity primary key,
  call_id text not null,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  signal_type text not null check (signal_type in ('offer','answer','ice','reject','end','busy','renegotiate-offer','renegotiate-answer')),
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists call_signals_recipient_created_idx
  on public.call_signals (recipient_id, created_at desc);
create index if not exists call_signals_call_id_idx
  on public.call_signals (call_id, created_at asc);
alter table public.call_signals enable row level security;
drop policy if exists "call signals participants can read" on public.call_signals;
create policy "call signals participants can read" on public.call_signals
  for select to authenticated
  using (auth.uid() = sender_id or auth.uid() = recipient_id);
drop policy if exists "call signals sender inserts" on public.call_signals;
create policy "call signals sender inserts" on public.call_signals
  for insert to authenticated
  with check (auth.uid() = sender_id and sender_id <> recipient_id);
-- Realtime must be enabled for call_signals from Supabase Dashboard > Database > Replication
-- if it is not already part of the supabase_realtime publication.
do $$ begin
  alter publication supabase_realtime add table public.call_signals;
exception when duplicate_object then null;
when undefined_object then null;
end $$;
